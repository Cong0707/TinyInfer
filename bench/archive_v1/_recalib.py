print("=== 用官方 184 tok/s 反推真实机制 ===")
print()
OFFICIAL = 184.3          # tok/s, Artificial Analysis measured
ms_per_tok = 1000 / OFFICIAL
print(f"官方单流: {OFFICIAL} tok/s = {ms_per_tok:.2f} ms/token")
print()
print("如果这 5.4 ms 全用来读 9.24 GB 权重，需要带宽:")
need = 9.24 / (ms_per_tok/1000)
print(f"  9.24 GB / {ms_per_tok:.2f} ms = {need:.0f} GB/s = {need/1000:.1f} TB/s")
print(f"  1 张 H200 = 4.8 TB/s，所以 {need/4800:.2f} 张卡就够")
print()
print("但 DeepSeek 官方部署不可能只用 1 张卡跑 700B 模型。")
print("所以真实机制是：实际读取量远小于 9.24 GB。")
print()
print("=== 反推每 token 实际读多少 ===")
print("假设官方用 8 x H200 (38.4 TB/s)，5.4 ms 内能读:")
read_8 = 38.4 * (ms_per_tok/1000)
print(f"  38.4 TB/s x {ms_per_tok:.2f} ms = {read_8:.2f} GB")
print(f"  而我的最坏情况估计是 9.24 GB -> 实际只读了 {read_8/9.24*100:.0f}%")
print()
print("=== 那 9.24 GB 里哪些是重复读的？ ===")
print("  1. 专家 3.96 GB：同一批请求若路由到相同专家，只读一次")
print("  2. dense 4.67 GB：L2 命中（H200 60MB/卡 x 8 = 480MB）")
print("     但每层 dense 175 MB，40 层轮流 -> L2 装不下全部")
print("  3. head 0.62 GB：每 token 必读")
print()
print("=== 关键洞察：TP=8 时每卡只读 1/8 ===")
per_card = 9.24 / 8
print(f"  每卡每 token 读 {per_card:.2f} GB")
print(f"  单卡 4.8 TB/s -> {per_card/4.8*1000:.2f} ms")
print(f"  但 8 卡并行同一层，所以总时间仍是 {per_card/4.8*1000:.2f} ms")
print(f"  -> {1000/(per_card/4.8*1000):.0f} tok/s  这和官方 184 同量级！")