print("deq4 一次只覆盖 nibble 0,1,4,5（不是 0,1,2,3）")
print("要覆盖全部 8 个 nibble，需要：")
print("  deq4(word)         -> nibble 0,4 low / 1,5 high")
print("  deq4(word >> 8)    -> nibble 2,6 low / 3,7 high")
