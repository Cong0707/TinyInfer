print("=== 分析 lop3 解码的位布局 ===")
print()
LO = 0x000f000f
HI = 0x00f000f0
EX = 0x64006400
print(f"EX = 0x{EX:08x}  (两个 fp16 半字，每个 = 0x6400 = 1024.0)")
print(f"LO = 0x{LO:08x}  (每个半字取低 4 bit)")
print(f"HI = 0x{HI:08x}  (每个半字取高 4 bit)")
print()
print("所以 lop3(q, LO, EX) = (q & 0x000f000f) | 0x64006400")
print("  对 q 的 32 bit：")
print("    低半字 bits 0-15  -> 取 bit0-3，加上 0x6400")
print("    高半字 bits 16-31 -> 取 bit16-19，加上 0x6400")
print()
print("也就是说 lop3 一次处理【2 个 nibble】：nibble0 和 nibble4")
print("  lo 的两个 fp16 = decode(nibble0), decode(nibble4)")
print("  hi 的两个 fp16 = decode(nibble1), decode(nibble5)  <- HI mask 是 0x00f000f0")
print()
print("验证：输入 nibble 0..7 = [0,1,2,3,4,5,6,7]")
print("  lo 应该 = decode(0), decode(4) = 0-8, 4-8 = -8, -4")
print("  hi 应该 = decode(1), decode(5) = 1-8, 5-8 = -7, -3")
print("  实测前 4 个: [-8, -4, -7, -3]  <-- 完全吻合！")
print()
