print('RESULT === 核心矛盾：带宽 vs 容量 ===')
print('  300 tok/s 需要 3307 GB/s（100% 效率）')
print('  但 475.3 GB 模型必须全部常驻，否则退回 PCIe/磁盘')
print()
print('RESULT 单卡要同时满足: 带宽 >= 3307 且 显存 >= 475.3')
print('  没有一张卡同时满足：')
print('    H100 SXM  3350 GB/s 但 80GB   -> 带宽够，容量差 6 倍')
print('    B300      8000 GB/s 但 288GB  -> 带宽够，容量差 1.65 倍')
print()
print('RESULT === 多卡方案 ===')
print('  模型 475.3 GB 拆到 N 张卡，每卡搬 11.02/N GB/token')
print('  但每卡的带宽不变，所以总有效带宽 = N x 单卡带宽')
print()
for name, bw, cap in [('H100 SXM', 3350, 80), ('H100 NVL', 3900, 94), ('H200', 4800, 141), ('B300', 8000, 288)]:
    n = int(-(-475.3 // cap))
    total_bw = n * bw
    tok = total_bw / 11.02
    print('  %-10s %3dGB x %d 张 = %5d GB/s -> 100%% 时 %.1f tok/s' % (name, cap, n, total_bw, tok))
print()
print('RESULT === 但多卡有通信开销 ===')
print('  每层 MoE 后要 AllReduce（TP）或 AllToAll（EP）')
print('  40 层 x 2 次同步 x (11.02/N) 数据量')
print('  以 H200 8 卡为例：每卡 141GB，需 4 张')
print('  每 token 每卡搬 11.02/4 = 2.76 GB / 4.8 TB/s = 0.57ms')
print('  加上 AllReduce: 40 层 x 2 x 2.76GB 走 NVLink 900GB/s = 0.25ms')
print('  => 约 0.82ms = 1220 tok/s（理论）')
print()
print('RESULT === 结论 ===')
print('  300 tok/s 需要:')
print('    单卡 -> B300 有 2.4x 余量，但 288GB 装不下，必须 2 张')
print('    或      H100 x6 / H200 x4 / B300 x2')
print('  且 kernel 必须达到带宽的 41%%（单卡）或更低（多卡有余量）')